def area(a, b):
    '''
    Принимает стороны прямоугольника a и b, возвращает его площадь.

    Формула:
        a * b

    Параметры:
        a (int/float): длина первой стороны прямоугольника
        b (int/float): длина второй стороны прямоугольника

    Возвращаемое значение:
        int/float, площадь прямоугольника

    Пример вызова:
        area(3, 4) -> 12
    '''
    return a * b


def perimeter(a, b):
    '''
    Принимает стороны прямоугольника a и b, возвращает его периметр.

    Формула:
        2 * (a + b)

    Параметры:
        a (int/float): длина первой стороны прямоугольника
        b (int/float): длина второй стороны прямоугольника

    Возвращаемое значение:
        int/float, периметр прямоугольника

    Пример вызова:
        perimeter(3, 4) -> 14
    '''
    return 2 * (a + b)
